// Builds worker.js: the shared beane.ca password gate (gate/auth_gate.js, copied from thetruebeane/tests scripts/auth_gate.js)
// in front of the static game files. Run: node gate/build.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const site = { name: "Slope", sub: "slope.beane.ca", bg: "background-color:#0b0b0b" };
let gate = fs.readFileSync(path.join(dir, "auth_gate.js"), "utf8");
// Every path is a static asset behind the gate: no inlined demo page.
const from = 'const isDemo = path === "/" || path === "/index.html" || extra !== null;';
if (!gate.includes(from)) throw new Error("auth_gate.js changed: update gate/build.mjs");
gate = gate.replace(from, "const isDemo = false;");
const out = `// GENERATED by gate/build.mjs. Do not edit.\nconst HTML = "";\nconst SITE = ${JSON.stringify(site)};\n` + gate;
fs.writeFileSync(path.join(dir, "..", "worker.js"), out);
console.log("built worker.js", Buffer.byteLength(out), "bytes");
